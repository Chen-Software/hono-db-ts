	// Mutation endpoints (the former SSR POST handlers, now behind the service
	// layer). They return 3xx redirects so the SSR route can stream them
	// straight back to the browser.
	// ------------------------------------------------------------------

	// POST /page/repositories — create a repository (owner = current user).
	app.post('/page/repositories', async (c) => {
		const body = await c.req.parseBody()
		const name = typeof body['name'] === 'string' ? body['name'].trim() : ''
		const description = typeof body['description'] === 'string' ? body['description'].trim() : ''
		const isPrivate = body['isPrivate'] === '1' || body['isPrivate'] === 'on'
		const session = await getSession(c).catch(() => null)
		if (!session?.user) return c.redirect('/repositories?status=error&reason=auth&new=1')
		// Materialise the Better Auth user into the domain `users` table BEFORE
		// stamping ownerId, or the repositories.ownerId FK (→ users.id) will fail
		// for a freshly signed-up user who has never been resolved by the user
		// service. ensureUser uses the session user id as users.id and is idempotent.
		// (db is already bound by the service factory — pass only the session.)
		const ownerId = await svc.users.ensureUser(session)
		if (!ownerId) return c.redirect('/repositories?status=error&reason=auth&new=1')
		if (!name) return c.redirect('/repositories?status=error&reason=missing&new=1')
		const lowerName = name.toLowerCase().replace(/\s+/g, '-')
		try {
			await svc.repository.create({ ownerId, name, lowerName, description, isPrivate })
		} catch (err) {
			if (err instanceof InvalidRepositoryNameError) {
				return c.redirect('/repositories?status=error&reason=invalid&new=1')
			}
			if (err instanceof DuplicateRepositoryError) {
				return c.redirect('/repositories?status=error&reason=duplicate&new=1')
			}
			console.error('[POST /page/repositories] create failed:', err)
			return c.redirect('/repositories?status=error&reason=exception&new=1')
		}
		return c.redirect('/repositories?status=created')
	})

	// POST /page/repositories/:id/edit — save edited fields.
	app.post(`/page/repositories/:id/edit`, async (c) => {
		const id = c.req.param('id')
		const body = await c.req.parseBody()
		if (typeof body['action'] !== 'string' || body['action'] !== 'save') return c.redirect(`/repositories/${id}/edit`)
		const name = typeof body['name'] === 'string' ? body['name'].trim() : ''
		const lowerName = typeof body['lowerName'] === 'string' ? body['lowerName'].trim() : ''
		const description = typeof body['description'] === 'string' ? body['description'].trim() : ''
		const isPrivate = body['isPrivate'] === '1' || body['isPrivate'] === 'on'
		if (name && lowerName) {
			try {
				await svc.repository.update(id, { name, lowerName, description, isPrivate })
			} catch {
				return c.redirect(`/repositories/${id}/edit`)
			}
		}
		return c.redirect(`/repositories/${id}`)
	})

	// Anything unmatched — 404.
	app.notFound((c) => fail(`no route for ${c.req.method} ${c.req.path}`, 404))

