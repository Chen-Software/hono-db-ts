/**
 * http/app — the reusable Hono query app.
 *
 * Extracted from `scripts/serve.ts` so the SAME app can be mounted by both:
 *   - the local dev server  (`scripts/serve.ts` → `Bun.serve`),
 *   - the Cloudflare Worker (`src/worker.ts` → `export default { fetch }`).
 *
 * It is client-agnostic: it takes any SQL executor (Bun's `SQL`, or the Workers
 * `D1Executor`) and binds it to the **service layer** (`@/services`) via
 * `createServices`. Every handler now calls a service function — there is no
 * inline `sql.unsafe` here. All user input reaches SQL through the `?` bind
 * params the services use, so the dangerous interpolation pattern is gone.
 *
 * Two endpoint groups:
 *   - Browser-facing `/api/*` read models + generated CRUD (servable) + the
 *     `/page/*` composite endpoints the SSR route handlers fetch over HTTP.
 *
 * Endpoints:
 *   GET /stats, /repositories, /repositories/:id, /users/:id, /search
 *   GET /repositories/aggregate, /users/aggregate    (generated by Aggregable)
 *   GET /page/home, /page/repositories, /page/repositories/:id,
 *   /page/repositories/:id/edit, /page/users/:id
 *   POST /page/repositories (create), /page/repositories/:id/edit (save)
 */

